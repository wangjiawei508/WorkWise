const assert = require('node:assert/strict')
const { readFileSync, writeFileSync } = require('node:fs')
const { app, session } = require('electron')
const { CancellationToken } = require('builder-util-runtime')
const { ElectronHttpExecutor, getNetSession } = require('electron-updater/out/electronHttpExecutor')
const { GenericProvider } = require('electron-updater/out/providers/GenericProvider')

app.whenReady().then(async () => {
  const config = JSON.parse(readFileSync(process.argv.at(-1), 'utf8'))
  const { installPrivateUpdaterTls } = require(config.helper)
  const policy = { feedUrl: config.feedUrl, certificateSha256: config.certificateSha256 }
  const wrongPin = session.fromPartition('private-preflight-wrong-pin', { cache: false })
  installPrivateUpdaterTls(wrongPin, { ...policy, certificateSha256: '0'.repeat(64) })
  await assert.rejects(wrongPin.fetch(`${config.feedUrl}latest-mac.yml`))
  const plain = session.fromPartition('private-preflight-default-trust', { cache: false })
  await assert.rejects(plain.fetch(`${config.feedUrl}latest-mac.yml`))
  const updaterSession = getNetSession()
  assert.equal(require('electron-updater').autoUpdater.netSession, updaterSession)
  installPrivateUpdaterTls(updaterSession, policy)
  await assert.rejects(updaterSession.fetch(config.feedUrl.replace(/:\d+\//, ':1/')))
  await assert.rejects(updaterSession.fetch(new URL('/outside', config.feedUrl).href))
  const executor = new ElectronHttpExecutor()
  const provider = new GenericProvider({ provider: 'generic', url: config.feedUrl }, { isAddNoCacheQuery: true }, { executor, platform: 'darwin', isUseMultipleRangeRequest: false })
  const metadata = await provider.getLatestVersion()
  assert.equal(metadata.version, '0.5.0')
  const file = provider.resolveFiles(metadata)[0]
  await executor.download(file.url, config.download, { cancellationToken: new CancellationToken(), sha512: file.info.sha512 })
  assert.equal(readFileSync(config.download, 'utf8'), config.expectedBytes)
  writeFileSync(config.result, JSON.stringify({ status: 'passed', defaultTrustRejected: true, wrongPinRejected: true, wrongPortRejected: true, outsidePathRejected: true, providerManifestVerified: true, executorZipVerified: true, updaterSessionMatched: true }))
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
